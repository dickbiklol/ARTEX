package db

import (
	"encoding/json"
	_ "embed"
	"fmt"
)

// Built-in command recipes.
//
// A "recipe" is a scanner wrapper (nuclei / ffuf / dalfox / sqlmap …) expressed as
// data rather than as a Go tool: a description, a JSON-Schema for its parameters,
// and a shell template with {param} / {{#param}}…{{/param}} placeholders. They are
// seeded into the same `tools` table as user-defined custom tools (kind='command')
// so they get the same per-agent binding, on/off switch and deferred-schema
// handling — but with system=true so the UI protects them from deletion.
//
// Why data and not code: the value is in the parameter surface handed to the model
// (typed `nuclei(target, severity, tags)` beats "remember to type the right bash"),
// not in bespoke Go logic. Keeping them as rows also means an operator can disable
// or re-bind one scanner without a rebuild.
//
// The JSON is generated by scripts/yaml2artex from a CyberStrikeAI tools/*.yaml
// tree (Apache-2.0); see THIRD_PARTY.md.

//go:embed toolrecipes.json
var toolRecipesJSON []byte

// Recipe is one seeded command recipe.
type Recipe struct {
	Key         string          `json:"key"`
	Description string          `json:"description"`
	Schema      json.RawMessage `json:"schema"`
	Exec        json.RawMessage `json:"exec"`
	Agents      []string        `json:"agents"`
	Deferred    bool            `json:"deferred"`
}

// ToolRecipes returns the embedded built-in recipes. A malformed payload is a build
// artefact bug, so it is reported rather than silently ignored.
func ToolRecipes() ([]Recipe, error) {
	var out []Recipe
	if err := json.Unmarshal(toolRecipesJSON, &out); err != nil {
		return nil, fmt.Errorf("parse embedded tool recipes: %w", err)
	}
	return out, nil
}

// SeedToolRecipe inserts a built-in command recipe ONCE (ON CONFLICT DO NOTHING),
// so operator edits to description/schema/agents/enabled survive restarts — the
// same contract as SeedTool. system=true keeps it out of DeleteCustomTool's reach
// while still allowing the UI to disable it or rebind it to other agents.
func (d *DB) SeedToolRecipe(r Recipe) error {
	if r.Key == "" {
		return fmt.Errorf("recipe key is empty")
	}
	schema, exec := r.Schema, r.Exec
	if len(schema) == 0 {
		schema = json.RawMessage("{}")
	}
	if len(exec) == 0 {
		return fmt.Errorf("recipe %q has no exec spec", r.Key)
	}
	agents, err := json.Marshal(r.Agents)
	if err != nil || len(agents) == 0 {
		agents = json.RawMessage("[]")
	}
	_, err = d.Exec(`
INSERT INTO tools(key, system, description, schema, agents, enabled, kind, exec, deferred)
VALUES ($1, true, $2, $3, $4, true, 'command', $5, $6)
ON CONFLICT (key) DO NOTHING`,
		r.Key, r.Description, schema, agents, exec, r.Deferred)
	return err
}

// ListExecutableTools returns every enabled row that carries an execution spec:
// user-defined custom tools AND built-in command recipes. kind='builtin' rows are
// code-backed tools with no exec spec, and kind='shell' is an environment hint
// consumed by ToolResolve (it must not become a callable tool), so both are excluded.
func (d *DB) ListExecutableTools() ([]*Tool, error) {
	rows, err := d.Query(`SELECT ` + toolCols + ` FROM tools
WHERE enabled AND kind IN ('command','script','http')
ORDER BY key`)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	var out []*Tool
	for rows.Next() {
		t, err := scanTool(rows)
		if err != nil {
			return nil, err
		}
		out = append(out, t)
	}
	return out, rows.Err()
}
